/* =========================================================================
 * UTF-8 Stream Decoder — zero allocation
 * ========================================================================= */
uint32_t bb_utf8_decode_next(const char **ptr, const char *end) {
    if (!ptr || !*ptr) return 0;

    const unsigned char *p = (const unsigned char *)*ptr;

    /* honour explicit end; otherwise treat NUL as terminator */
    if (end) {
        if ((const char *)p >= end) return 0;
    } else {
        if (*p == '\0') return 0;
    }

    unsigned char b0 = *p;

    /* --- Single-byte ASCII (0x00–0x7F) ---------------------------------- */
    if (b0 < 0x80) {
        *ptr += 1;
        return (uint32_t)b0;
    }

    /* Determine how many bytes remain in the stream */
    size_t rem = end ? (size_t)((const unsigned char *)end - p) : 4;

    uint32_t cp = BB_UNICODE_REPLACEMENT;
    int      len = 1; /* consume at least one byte on error */

    if ((b0 & 0xE0) == 0xC0) {
        /* --- 2-byte sequence (U+0080..U+07FF) --------------------------- */
        if (rem >= 2 && (p[1] & 0xC0) == 0x80) {
            uint32_t v = ((uint32_t)(b0 & 0x1F) << 6) | (uint32_t)(p[1] & 0x3F);
            if (v >= 0x80) { cp = v; len = 2; }
        }
    } else if ((b0 & 0xF0) == 0xE0) {
        /* --- 3-byte sequence (U+0800..U+FFFF, excl. surrogates) --------- */
        if (rem >= 3 && (p[1] & 0xC0) == 0x80 && (p[2] & 0xC0) == 0x80) {
            uint32_t v = ((uint32_t)(b0 & 0x0F) << 12)
                       | ((uint32_t)(p[1] & 0x3F) <<  6)
                       |  (uint32_t)(p[2] & 0x3F);
            if (v >= 0x800 && (v < 0xD800 || v > 0xDFFF)) { cp = v; len = 3; }
        }
    } else if ((b0 & 0xF8) == 0xF0) {
        /* --- 4-byte sequence (U+10000..U+10FFFF) ------------------------ */
        if (rem >= 4 && (p[1] & 0xC0) == 0x80 && (p[2] & 0xC0) == 0x80 && (p[3] & 0xC0) == 0x80) {
            uint32_t v = ((uint32_t)(b0 & 0x07) << 18)
                       | ((uint32_t)(p[1] & 0x3F) << 12)
                       | ((uint32_t)(p[2] & 0x3F) <<  6)
                       |  (uint32_t)(p[3] & 0x3F);
            if (v >= 0x10000 && v <= 0x10FFFF) { cp = v; len = 4; }
        }
    }
    /* else: continuation byte or invalid lead byte — consume 1 as replacement */

    *ptr += len;
    return cp;
}

/* =========================================================================
 * Unicode → internal glyph index (0..255)
 * ========================================================================= */
uint8_t bb_unicode_to_glyph(uint32_t cp) {
    /* Standard printable ASCII */
    if (cp >= 0x20 && cp <= 0x7E) return (uint8_t)cp;
    /* Non-breaking space → render as regular space glyph */
    if (cp == BB_UNICODE_NBSP) return 0x20;
    /* Latin-1 Supplement (0xA0–0xFF) maps 1:1 to our table */
    if (cp >= 0xA0 && cp <= 0xFF) return (uint8_t)cp;

    /* Common typographic replacements for characters above U+00FF */
    /* En dash, em dash → hyphen */
    if (cp == 0x2013 || cp == 0x2014) return '-';
    /* Left/right single quotation marks → apostrophe */
    if (cp == 0x2018 || cp == 0x2019) return '\'';
    /* Left/right double quotation marks → double-quote */
    if (cp == 0x201C || cp == 0x201D) return '"';
    /* Ellipsis → full stop */
    if (cp == 0x2026) return '.';
    /* Bullet → bullet glyph at index 0x07 */
    if (cp == 0x2022) return 0x07;
    /* Euro sign → glyph at 0x80 (Windows-1252 mapping) */
    if (cp == 0x20AC) return 0x80;
    /* Trademark, registered, copyright */
    if (cp == 0x2122) return 'T'; /* TM */
    if (cp == 0x00AE) return 0xAE;
    if (cp == 0x00A9) return 0xA9;

    /* Fallback: '?' */
    return '?';
}

