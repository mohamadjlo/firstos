void bb_font_init(void) { /* nothing needed */ }

int bb_font_get_char_width(char c, const bb_font_style_t *style) {
    (void)c;
    int scale = (style && style->scale > 0) ? style->scale : 1;
    return 8 * scale;
}

int bb_font_get_line_height(const bb_font_style_t *style) {
    int scale = (style && style->scale > 0) ? style->scale : 1;
    return 16 * scale + 2; /* 2px line gap */
}

/* Measure a UTF-8 string (number of codepoints × char_width, multi-line aware) */
void bb_font_measure_string(const char *text, const bb_font_style_t *style, int32_t *out_w, int32_t *out_h) {
    if (!text) {
        if (out_w) *out_w = 0;
        if (out_h) *out_h = 0;
        return;
    }

    int scale  = (style && style->scale > 0) ? style->scale : 1;
    int char_w = 8 * scale;
    int line_h = 16 * scale + 2;

    int max_line_w = 0;
    int cur_line_w = 0;
    int lines = 1;

    const char *p   = text;
    const char *end = NULL; /* NUL-terminated */

    while (true) {
        uint32_t cp = bb_utf8_decode_next(&p, end);
        if (cp == 0) break;

        if (cp == '\n') {
            if (cur_line_w > max_line_w) max_line_w = cur_line_w;
            cur_line_w = 0;
            lines++;
        } else if (cp == '\t') {
            cur_line_w += char_w * 4;
        } else {
            cur_line_w += char_w;
        }
    }
    if (cur_line_w > max_line_w) max_line_w = cur_line_w;

    if (out_w) *out_w = max_line_w;
    if (out_h) *out_h = lines * line_h;
}

/* Draw a single glyph given a raw index (0–255) */
static void draw_glyph(bb_raster_t *r, int32_t x, int32_t y, uint8_t glyph_idx,
                       bb_color_t color, const bb_font_style_t *style) {
    const uint8_t *bitmap = vga_font_8x16[glyph_idx];
    int scale     = (style && style->scale > 0) ? style->scale : 1;
    bool bold     = style ? style->bold     : false;
    bool italic   = style ? style->italic   : false;
    bool underline= style ? style->underline: false;

    for (int row = 0; row < 16; row++) {
        uint8_t bits = bitmap[row];
        if (bold) bits |= (bits >> 1);

        int32_t italic_offset = italic ? ((int32_t)((15 - row) / 4) * scale) : 0;
        int32_t py = y + row * scale;

        for (int col = 0; col < 8; col++) {
            if (bits & (0x80 >> col)) {
                int32_t px = x + col * scale + italic_offset;
                if (scale == 1) {
                    bb_raster_draw_pixel(r, px, py, color);
                } else {
                    bb_rect_t pbox = {px, py, scale, scale};
                    bb_raster_fill_rect(r, pbox, color);
                }
            }
        }
    }

    if (underline) {
        int32_t uy = y + 14 * scale;
        int32_t uw = 8 * scale;
        bb_rect_t uline = {x, uy, uw, scale};
        bb_raster_fill_rect(r, uline, color);
    }
}

/* Public single-char draw (keeps backward compatibility with ASCII callers) */
void bb_font_draw_char(bb_raster_t *r, int32_t x, int32_t y, char c,
                       bb_color_t color, const bb_font_style_t *style) {
    if (!r) return;
    uint8_t idx = (uint8_t)c;
    draw_glyph(r, x, y, idx, color, style);
}

/* Draw a NUL-terminated UTF-8 string.
 * U+00A0 (NBSP) advances cursor_x without creating a line-break opportunity.
 * All other whitespace handling (collapsing) is the caller's responsibility. */
void bb_font_draw_string(bb_raster_t *r, int32_t x, int32_t y,
                         const char *text, bb_color_t color,
                         const bb_font_style_t *style) {
    if (!r || !text) return;
    int scale  = (style && style->scale > 0) ? style->scale : 1;
    int char_w = 8 * scale;
    int line_h = 16 * scale + 2;

    int32_t cur_x = x;
    int32_t cur_y = y;
    const char *p = text;

    while (true) {
        uint32_t cp = bb_utf8_decode_next(&p, NULL);
        if (cp == 0) break;

        if (cp == '\n') {
            cur_x = x;
            cur_y += line_h;
        } else if (cp == '\r') {
            /* ignore CR */
        } else if (cp == '\t') {
            cur_x += char_w * 4;
        } else if (cp == BB_UNICODE_NBSP) {
            /* Non-breaking space: advance cursor, no line-break opportunity here */
            cur_x += char_w;
        } else {
            uint8_t gidx = bb_unicode_to_glyph(cp);
            draw_glyph(r, cur_x, cur_y, gidx, color, style);
            cur_x += char_w;
        }
    }
}
